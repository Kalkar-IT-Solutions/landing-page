const languages = { de, en };

function initialLanguage() {
  const saved = store.get('lang');
  if (saved && languages[saved]) return saved;
  return (navigator.language ?? 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
}

export let lang = initialLanguage();

export function setLanguage(code) {
  lang = languages[code] ? code : 'de';
  store.set('lang', lang);
  document.documentElement.lang = lang;
}

/** The text for [key], called with [args] when it is a function. */
export function t(key, ...args) {
  const entry = languages[lang][key];
  return typeof entry === 'function' ? entry(...args) : entry ?? key;
}

/** A field of a seed entry in the current language: value_en over value. */
export function local(obj, field) {
  if (!obj) return '';
  return (lang === 'en' && obj[`${field}_en`]) || obj[field] || '';
}

const locale = () => (lang === 'en' ? 'en-GB' : 'de-DE');

export const fmt = {
  time: (d) => d.toLocaleTimeString(locale(), { hour: '2-digit', minute: '2-digit' }),
  date: (d) => d.toLocaleDateString(locale(), { day: 'numeric', month: 'long', year: 'numeric' }),
  shortDate: (d) => d.toLocaleDateString(locale(), { weekday: 'short', day: 'numeric', month: 'short' }),
  /** "3. Dez. – 6. Jan." for two days "YYYY-MM-DD". */
  dayMonthRange(from, to) {
    const opts = { day: 'numeric', month: 'short' };
    const day = (d) => new Date(`${d}T00:00:00`).toLocaleDateString(locale(), opts);
    return `${day(from)} – ${day(to)}`;
  },
  weekday: (d) => d.toLocaleDateString(locale(), { weekday: 'long', day: 'numeric', month: 'long' }),
  weekdayShort: (d) => d.toLocaleDateString(locale(), { weekday: 'short' }),
  /** "heute 14:30", "morgen 9:00" or "Mi., 3. Dez. 9:00". */
  when(d, now = new Date()) {
    const days = Math.round((new Date(d.getFullYear(), d.getMonth(), d.getDate()) - new Date(now.getFullYear(), now.getMonth(), now.getDate())) / 86400000);
    const day = days === 0 ? t('daysUntil', 0) : days === 1 ? t('daysUntil', 1) : fmt.shortDate(d);
    return `${day} ${fmt.time(d)}`;
  },
  number: (n, digits = 0) => n.toLocaleString(locale(), { maximumFractionDigits: digits, minimumFractionDigits: digits }),
  celsius: (n) => `${fmt.number(n, 1)} °C`,
  cm: (n) => `${fmt.number(n)} cm`,
  percent: (n) => `${fmt.number(n)} %`,
  kmh: (n) => `${fmt.number(n)} km/h`,
  mm: (n) => `${fmt.number(n, 1)} mm`,
};
